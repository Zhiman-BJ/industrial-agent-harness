const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {createDiagnosticLog, projectLogDirectory} = require('../src/diagnostic-log.cjs');
const {DiagnosticReader} = require('../src/diagnostic-reader.cjs');
function fixture(t) {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'harness-log-reader-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const project=path.join(root,'project'),other=path.join(root,'other'),directory=path.join(root,'logs');
  fs.mkdirSync(project);fs.mkdirSync(other);
  const reader=new DiagnosticReader(directory);
  return {root,project,other,directory,reader};
}
test('production logs expose raw tool results, compression and metrics, including UTF-8 chunks', async t=>{
  const {project,directory,reader}=fixture(t),log=createDiagnosticLog(project,{directory,apiKey:'model-secret'});
  log.record('run.start',{projectDir:project,model:{model:'test-model'}});
  log.record('sdk.event',{type:'ToolCall',payload:{id:'call-1',function:{name:'read_file',arguments:'{"path":"large.txt"}'}}});
  const output='工具内容🙂\n'.repeat(10000)+'FULL-END';
  log.record('sdk.event',{type:'ToolResult',payload:{tool_call_id:'call-1',return_value:{output,message:'model-secret',is_error:false}}});
  log.record('sdk.event',{type:'StatusUpdate',payload:{context_usage:.82,token_usage:{output:120}}});
  log.record('sdk.event',{type:'CompactionBegin',payload:{}});
  log.record('sdk.event',{type:'CompactionEnd',payload:{}});
  log.record('run.end',{status:'completed',metrics:{compactions:1}});log.close();
  const {runs}=await reader.list(project),runId=runs[0].runId;
  assert.equal(runs[0].traceId,log.traceId);assert.equal(runs[0].status,'completed');
  const tools=await reader.page(project,{runId,category:'tools'});
  assert.equal(tools.total,2);assert.equal(tools.records[0].summary,'read_file');
  assert.deepEqual((await reader.page(project,{runId,category:'context'})).records.map(row=>row.event),['StatusUpdate','CompactionBegin','CompactionEnd']);
  let raw='',offset=0,part;
  do {part=await reader.record(project,{runId,sequence:3,offset});assert.ok(Buffer.byteLength(part.text)<=65536);assert.ok(!part.text.includes('�'));raw+=part.text;offset=part.nextOffset;} while(offset!=null);
  assert.equal(JSON.parse(raw).payload.payload.return_value.output,output);
  assert.equal(JSON.parse(raw).payload.payload.return_value.message,'[REDACTED_API_KEY]');
  assert.deepEqual((await reader.page(project,{runId,query:'read_file'})).records.map(row=>row.sequence),[2]);
});
test('growing logs omit partial records, resume without duplicates, and page beyond 100 events', async t=>{
  const {project,directory,reader}=fixture(t),log=createDiagnosticLog(project,{directory});
  log.record('run.start',{});
  for(let i=0;i<130;i++)log.record('sdk.event',{type:'StatusUpdate',payload:{context_usage:i/200}});
  const runId=path.basename(log.file);
  const page=await reader.page(project,{runId});assert.equal(page.records.length,100);assert.equal(page.nextOffset,100);
  assert.equal((await reader.page(project,{runId,offset:100})).records.length,31);
  log.close();
  const record=JSON.stringify({schemaVersion:1,traceId:log.traceId,sequence:132,at:new Date().toISOString(),type:'run.end',payload:{status:'interrupted'}});
  fs.appendFileSync(log.file,record.slice(0,40));
  const partial=await reader.page(project,{runId});assert.equal(partial.pending,true);assert.equal(partial.totalRecords,131);
  fs.appendFileSync(log.file,record.slice(40)+'\n');
  const complete=await reader.page(project,{runId});assert.equal(complete.pending,false);assert.equal(complete.totalRecords,132);
  assert.equal((await reader.list(project)).runs[0].status,'interrupted');
});
test('reader rejects cross-project, traversal, symlink, corrupt identity and excessive requests', async t=>{
  const {root,project,other,directory,reader}=fixture(t),log=createDiagnosticLog(project,{directory});
  log.record('run.start',{});log.close();const runId=path.basename(log.file);
  assert.equal((await reader.list(other)).runs.length,0);
  await assert.rejects(reader.page(other,{runId}),/unavailable/);
  await assert.rejects(reader.page(project,{runId:'../'+runId}),/Invalid/);
  await assert.rejects(reader.page(project,{runId,offset:-1}),/Invalid/);
  await assert.rejects(reader.page(project,{runId,query:'x'.repeat(201)}),/Invalid/);
  const outside=path.join(root,'outside.jsonl');fs.copyFileSync(log.file,outside);fs.unlinkSync(log.file);fs.symlinkSync(outside,log.file);
  await assert.rejects(reader.record(project,{runId,sequence:1}));
  fs.unlinkSync(log.file);fs.copyFileSync(outside,log.file);
  fs.writeFileSync(log.file,fs.readFileSync(log.file,'utf8').replace(log.traceId,'00000000-0000-0000-0000-000000000000'));
  await assert.rejects(reader.page(project,{runId}),/identity/);
  fs.writeFileSync(log.file,'not json\n');await assert.rejects(reader.page(project,{runId}),/Malformed/);
  fs.unlinkSync(log.file);const fd=fs.openSync(log.file,'w');fs.ftruncateSync(fd,65*1024*1024);fs.closeSync(fd);
  await assert.rejects(reader.page(project,{runId}),/64 MiB/);
  fs.rmSync(projectLogDirectory(project,directory),{recursive:true});fs.symlinkSync(root,projectLogDirectory(project,directory));
  await assert.rejects(reader.list(project),/symlink/);
});
